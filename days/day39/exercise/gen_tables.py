"""Day 39: build three small SIMULATED tables for Cortex Analyst (seed 30 stays from Day 30/36, seed 39 extras).
Writes encounters.csv, patients.csv, drg_groups.csv and 02_load_tables.sql. No Snowflake needed.
All rows are invented for teaching. No real patients, no real hospital."""
import numpy as np
import pandas as pd
from sim_readmit import simulate

d = simulate(1000, 30)                                   # the same 2,655 stays as Days 30 and 36
d = d[d.admit_date < "2026-01-01"].reset_index(drop=True)  # keep calendar 2024-2025 so there are no future dates
rng = np.random.default_rng(39)

enc = pd.DataFrame({
    "ENCOUNTER_ID": [f"E{i:05d}" for i in range(1, len(d) + 1)],
    "PATIENT_ID": d.patient_id + 1001,
    "ADMIT_DATE": d.admit_date.dt.date,
    "DISCHARGE_DATE": (d.admit_date + pd.to_timedelta(np.maximum(1, d.los_days.round()), unit="D")).dt.date,
    "ADMIT_TYPE": d.admit_type,
    "DISCHARGE_DISPOSITION": d.discharge,
    "PAYER": d.payer,
    "DRG_CODE": d.drg,
    "LOS_DAYS": d.los_days,
    "AGE_AT_ADMIT": d.age.astype(int),
    "READMIT_30D": d.readmit30.astype(int),
})

pids = np.sort(enc.PATIENT_ID.unique())
counties = ["Marion", "Hamilton", "Hendricks", "Johnson", "Boone", "Hancock", "Madison", "Morgan", "Shelby"]
pat = pd.DataFrame({
    "PATIENT_ID": pids,
    "SEX": rng.choice(["F", "M"], len(pids), p=[.52, .48]),
    "HOME_COUNTY": rng.choice(counties, len(pids), p=[.34, .17, .11, .10, .06, .06, .07, .05, .04]),
    "FIRST_ADMIT_DATE": enc.groupby("PATIENT_ID").ADMIT_DATE.min().loc[pids].values,
})

named = {
    "291": ("Heart failure and shock with MCC", "Cardiology"),
    "871": ("Septicemia or severe sepsis with MCC", "Infectious disease"),
    "470": ("Major hip and knee joint replacement", "Orthopedics"),
    "190": ("COPD with MCC", "Pulmonary"),
    "392": ("Esophagitis, gastroenteritis and digestive disorders", "Gastroenterology"),
    "683": ("Renal failure with CC", "Nephrology"),
    "690": ("Kidney and urinary tract infections", "Nephrology"),
    "193": ("Simple pneumonia and pleurisy with MCC", "Pulmonary"),
    "603": ("Cellulitis", "General medicine"),
    "378": ("GI hemorrhage with CC", "Gastroenterology"),
}
line_of = dict(zip("IJKNAEMFL", ["Cardiology", "Pulmonary", "Gastroenterology", "Nephrology", "Infectious disease",
                                 "Endocrinology", "Orthopedics", "Behavioral health", "General medicine"]))
codes = sorted(set(simulate.day30_tail) | set(named))
drg = pd.DataFrame({
    "DRG_CODE": codes,
    "DRG_DESCRIPTION": [named[c][0] if c in named else f"Other DRG {c} (simulated)" for c in codes],
    "SERVICE_LINE": [named[c][1] if c in named else line_of["IJKNAEMFL"[int(c) % 9]] for c in codes],
})

enc.to_csv("encounters.csv", index=False)
pat.to_csv("patients.csv", index=False)
drg.to_csv("drg_groups.csv", index=False)


def lit(v):
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    if hasattr(v, "isoformat"):
        return f"'{v.isoformat()}'"
    return str(v)


def inserts(table, df, size=500):
    out = []
    for s in range(0, len(df), size):
        rows = [",".join(lit(v) for v in r) for r in df.iloc[s:s + size].itertuples(index=False)]
        out.append(f"INSERT INTO {table} VALUES\n(" + "),\n(".join(rows) + ");")
    return "\n".join(out)


sql = f"""-- Day 39: load three SIMULATED tables into DS90.DAY39 (generated by gen_tables.py, seed 30 + 39).
-- {len(enc):,} encounters, {len(pat):,} patients, {len(drg)} DRG rows. Invented data, not real patients.
-- Run after 01_setup.sql in a Snowsight worksheet (Run All). About 10 seconds on X-Small.
USE WAREHOUSE DS90_XS;
USE SCHEMA DS90.DAY39;

CREATE OR REPLACE TABLE DRG_GROUPS (
  DRG_CODE VARCHAR(3) NOT NULL PRIMARY KEY,
  DRG_DESCRIPTION VARCHAR,
  SERVICE_LINE VARCHAR
) COMMENT = 'Simulated DRG lookup. Short real-style labels, simulated codes list.';

CREATE OR REPLACE TABLE PATIENTS (
  PATIENT_ID NUMBER NOT NULL PRIMARY KEY,
  SEX VARCHAR(1),
  HOME_COUNTY VARCHAR,
  FIRST_ADMIT_DATE DATE
) COMMENT = 'Simulated patients (seed 39 extras). Not real people.';

CREATE OR REPLACE TABLE ENCOUNTERS (
  ENCOUNTER_ID VARCHAR(6) NOT NULL PRIMARY KEY,
  PATIENT_ID NUMBER NOT NULL,
  ADMIT_DATE DATE,
  DISCHARGE_DATE DATE,
  ADMIT_TYPE VARCHAR,
  DISCHARGE_DISPOSITION VARCHAR,
  PAYER VARCHAR,
  DRG_CODE VARCHAR(3),
  LOS_DAYS NUMBER(5,1),
  AGE_AT_ADMIT NUMBER(3,0),
  READMIT_30D NUMBER(1,0)
) COMMENT = 'Simulated inpatient stays 2024-2025 (Day 30/36 generator, seed 30). READMIT_30D = 1 if readmitted within 30 days.';

{inserts('DRG_GROUPS', drg)}

{inserts('PATIENTS', pat)}

{inserts('ENCOUNTERS', enc)}

-- Expect {len(drg)} / {len(pat):,} / {len(enc):,}
SELECT 'DRG_GROUPS' AS T, COUNT(*) AS N FROM DRG_GROUPS
UNION ALL SELECT 'PATIENTS', COUNT(*) FROM PATIENTS
UNION ALL SELECT 'ENCOUNTERS', COUNT(*) FROM ENCOUNTERS;
SELECT ROUND(AVG(READMIT_30D), 3) AS READMIT_RATE, MIN(ADMIT_DATE), MAX(DISCHARGE_DATE) FROM ENCOUNTERS;
"""
open("02_load_tables.sql", "w").write(sql)
print(f"encounters {len(enc)}, patients {len(pat)}, drg {len(drg)}, readmit rate {enc.READMIT_30D.mean():.3f}, "
      f"admit {enc.ADMIT_DATE.min()} to {enc.ADMIT_DATE.max()}, discharge max {enc.DISCHARGE_DATE.max()}")
